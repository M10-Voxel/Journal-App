/** Decode the original device key; formatting changes must not change the vault ID. */
export function parseDeviceKey(text:string,en=false):Uint8Array {
  const invalid=()=>new Error(en
    ? 'Invalid device key. Paste the full key generated by Journal (normally 44 characters). This field is not a password. Use the original key from your first device; do not generate a replacement for existing cloud data.'
    : 'Ungültiger Geräteschlüssel. Füge den vollständigen, von Journal erzeugten Schlüssel ein (normalerweise 44 Zeichen). Dieses Feld ist kein Passwort. Verwende den ursprünglichen Schlüssel vom ersten Gerät; erzeuge für bestehende Cloud-Daten keinen neuen.');
  const normalized=text.replace(/[\s\u200B-\u200D\uFEFF]/gu,'').replace(/-/g,'+').replace(/_/g,'/');
  if(!/^[A-Za-z0-9+/]{43}=?$/.test(normalized))throw invalid();
  try {
    const bytes=Uint8Array.from(atob(normalized),c=>c.charCodeAt(0));
    // Canonical padding bits prevent accepting a mistyped final character.
    if(bytes.length!==32||btoa(String.fromCharCode(...bytes)).replace(/=+$/,'')!==normalized.replace(/=+$/,''))throw invalid();
    return bytes;
  }catch{throw invalid();}
}
