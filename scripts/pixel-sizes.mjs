// Writes src/pixel-sizes.css: in the pixel theme every small text (11 px and below) a size up, as the pixel faces have
// small letters there – VT323 (mono) much more than Pixelify Sans. Rules in pixel.css come later and win.
// Run again after changing small font sizes: node scripts/pixel-sizes.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const files = ['styles.css', 'calendar.css', 'mail.css', 'colors.css', 'tags.css'];
const out = [];
for (const file of files) {
  const css = readFileSync(new URL(`../src/${file}`, import.meta.url), 'utf8');
  for (const line of css.split('\n')) {
    // Only top-level, one-line rules (nested @media rules keep their own sizes).
    const rule = /^([^\s@:/{][^{]*|:where[^{]*|:is[^{]*)\{(.*)\}\s*$/.exec(line);
    if (!rule || rule[1].includes("data-theme='pixel'")) continue;
    const body = rule[2];
    const shorthand = /(?:^|;)\s*font:\s*(?:(\d{3})\s+)?(\d+(?:\.\d+)?)px(?:\/[\d.]+px)?\s+var\(--(mono|sans|write)\)/.exec(body);
    const size = shorthand ? Number(shorthand[2]) : Number(/(?:^|;)\s*font-size:\s*(\d+(?:\.\d+)?)px/.exec(body)?.[1] ?? NaN);
    if (!(size <= 11)) continue;
    const mono = shorthand ? shorthand[3] !== 'sans' : /var\(--(mono|write)\)/.test(body);
    const next = Math.round(size * (mono ? 1.3 : 1.15) * 2) / 2;
    const selectors = rule[1].trim().split(/,(?![^(]*\))/).map(selector => `:root[data-theme='pixel'] ${selector.trim()}`);
    out.push(`${selectors.join(', ')} { font-size: ${next}px; }`);
  }
}
writeFileSync(new URL('../src/pixel-sizes.css', import.meta.url), `/* Generated by scripts/pixel-sizes.mjs – small texts a size up in the pixel theme. */\n${out.join('\n')}\n`);
console.log(`${out.length} rules`);
